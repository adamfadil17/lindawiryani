async function seedContent() {
  if (snapshot.schemaVersion !== 1) {
    throw new Error(`Unsupported seed schema version: ${snapshot.schemaVersion}`);
  }

  await seedCategories();
  await seedDestinations();
  await seedExperiences();
  await seedVenues();
  await seedThemes();
  await seedPortfolios();
  await seedArticles();
  await seedPositions();

  const counts = {
    categories: await prisma.destinationCategory.count(),
    destinations: await prisma.destination.count(),
    experiences: await prisma.weddingExperience.count(),
    faqs: await prisma.experienceFaq.count(),
    venues: await prisma.venue.count(),
    themes: await prisma.weddingTheme.count(),
    portfolios: await prisma.portfolio.count(),
    articles: await prisma.article.count(),
    positions: await prisma.openPosition.count(),
  };

  console.log("Content seed complete:", counts);
}

async function seedAdmin() {
  const email = process.env.ADMIN_EMAIL?.trim().toLowerCase();
  const password = process.env.ADMIN_PASSWORD;
  const name = process.env.ADMIN_NAME?.trim() || "Admin";

  if (!email || !password) {
    console.warn(
      "Skipping admin seed: ADMIN_EMAIL and ADMIN_PASSWORD are not set.",
    );
    return;
  }

  if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email)) {
    throw new Error(`ADMIN_EMAIL is not a valid email address: ${email}`);
  }

  if (password.length < 12) {
    throw new Error("ADMIN_PASSWORD must be at least 12 characters long.");
  }

  const existing = await prisma.user.findUnique({ where: { email } });
  if (existing) {
    console.log(`Admin user already exists: ${existing.email} (left unchanged).`);
    console.log("Run `npm run db:reset-admin` to rotate its password.");
    return;
  }

  const hashedPassword = await bcrypt.hash(password, 12);
  const admin = await prisma.user.create({
    data: { name, email, password: hashedPassword, role: "admin" },
  });
  console.log(`Admin user created: ${admin.email}`);
}

async function main() {
  await seedContent();
  await seedAdmin();
}

main()
  .catch((error) => {
    console.error("Seeding error:", error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
