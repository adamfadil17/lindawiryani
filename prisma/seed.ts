import bcrypt from "bcryptjs";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { prisma } from "../src/lib/prisma";
import { buildTranslationRows } from "../src/lib/content/translations";
import { sanitizeRichText } from "../src/lib/sanitize";
import type { TranslationEntity } from "../src/lib/content/translation-fields";

/**
 * Single seed entrypoint (`npm run db:seed`).
 *
 * 1. Content from prisma/seed-data/content.json.
 * 2. The first admin user when ADMIN_EMAIL / ADMIN_PASSWORD are set.
 *
 * Content rules:
 * - Every row is upserted by slug; UUIDs are generated by Prisma for new rows.
 * - The snapshot contains no IDs; relations are resolved through slug maps.
 * - Translations are replaced from the snapshot on every run.
 * - Galleries and experience FAQs are replaced from the snapshot.
 * - Content seeding never handles users, inquiries, or submissions.
 */

type Row = Record<string, any>;

interface Snapshot {
  schemaVersion: number;
  categories: Row[];
  destinations: Row[];
  experiences: Row[];
  venues: Row[];
  themes: Row[];
  portfolios: Row[];
  articles: Row[];
  positions: Row[];
}

const snapshot = JSON.parse(
  readFileSync(
    fileURLToPath(new URL("./seed-data/content.json", import.meta.url)),
    "utf8",
  ),
) as Snapshot;

const asDate = (value: unknown): Date | null =>
  value ? new Date(String(value)) : null;

function translationMutation(
  exists: boolean,
  entity: TranslationEntity,
  map: Row | undefined,
) {
  const rows = buildTranslationRows(entity, map);
  if (rows.length === 0) return exists ? { deleteMany: {} } : undefined;
  return exists
    ? { deleteMany: {}, create: rows as never }
    : { create: rows as never };
}

function galleryMutation(exists: boolean, gallery: Row[] | undefined) {
  const rows = (gallery ?? []).map((image) => ({
    url: image.url,
    sort_order: image.sort_order ?? 0,
  }));
  if (rows.length === 0) return exists ? { deleteMany: {} } : undefined;
  return exists ? { deleteMany: {}, create: rows } : { create: rows };
}

function publication(item: Row) {
  return {
    status: item.status ?? "published",
    published_at: asDate(item.published_at),
    first_published_at:
      asDate(item.first_published_at) ?? asDate(item.published_at),
  };
}

async function seedCategories() {
  for (const item of snapshot.categories) {
    const existing = await prisma.destinationCategory.findUnique({
      where: { slug: item.slug },
      select: { id: true },
    });
    const translations = translationMutation(
      Boolean(existing),
      "category",
      item.translations,
    );
    const data: any = {
      name: item.name,
      sort_order: item.sort_order ?? 0,
      ...publication(item),
      ...(translations ? { translations } : {}),
    };

    if (existing) {
      await prisma.destinationCategory.update({
        where: { id: existing.id },
        data,
      });
    } else {
      await prisma.destinationCategory.create({
        data: { slug: item.slug, ...data },
      });
    }
  }
}

async function seedDestinations() {
  const categories = new Map(
    (
      await prisma.destinationCategory.findMany({
        select: { id: true, slug: true },
      })
    ).map((row) => [row.slug, row.id]),
  );

  for (const item of snapshot.destinations) {
    const categoryId = categories.get(item.category_slug);
    if (!categoryId) {
      throw new Error(`Unknown category slug: ${item.category_slug}`);
    }

    const existing = await prisma.destination.findUnique({
      where: { slug: item.slug },
      select: { id: true },
    });
    const {
      category_slug: _categorySlug,
      translations: translationMap,
      published_at: _publishedAt,
      first_published_at: _firstPublishedAt,
      ...base
    } = item;

    const translations = translationMutation(
      Boolean(existing),
      "destination",
      translationMap,
    );
    const data: any = {
      ...base,
      category_id: categoryId,
      ...publication(item),
      ...(translations ? { translations } : {}),
    };

    if (existing) {
      await prisma.destination.update({
        where: { id: existing.id },
        data,
      });
    } else {
      await prisma.destination.create({ data });
    }
  }
}

async function seedExperiences() {
  for (const item of snapshot.experiences) {
    const existing = await prisma.weddingExperience.findUnique({
      where: { slug: item.slug },
      select: { id: true },
    });
    const {
      faqs,
      translations: translationMap,
      published_at: _publishedAt,
      first_published_at: _firstPublishedAt,
      ...base
    } = item;

    const translations = translationMutation(
      Boolean(existing),
      "experience",
      translationMap,
    );
    const data: any = {
      ...base,
      ...publication(item),
      ...(translations ? { translations } : {}),
    };

    const experience = existing
      ? await prisma.weddingExperience.update({
          where: { id: existing.id },
          data,
        })
      : await prisma.weddingExperience.create({ data });

    await prisma.experienceFaq.deleteMany({
      where: { experience_id: experience.id },
    });

    for (const faq of faqs ?? []) {
      const faqTranslations = translationMutation(
        false,
        "faq",
        faq.translations,
      );
      await prisma.experienceFaq.create({
        data: {
          slug: faq.slug,
          experience_id: experience.id,
          question: faq.question,
          answer: faq.answer,
          sort_order: faq.sort_order ?? 0,
          ...(faqTranslations ? { translations: faqTranslations } : {}),
        },
      });
    }
  }
}

